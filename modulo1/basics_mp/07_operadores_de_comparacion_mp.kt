fun main() {
    println("Operadores de Comparación")

    var asistentesEvento1 = 10
    var asistentesEvento2 = 2

    println("$asistentesEvento1 == $asistentesEvento2 : ${asistentesEvento1 == asistentesEvento2}")
    println("$asistentesEvento1 != $asistentesEvento2 : ${asistentesEvento1 != asistentesEvento2}")
    println("$asistentesEvento1 > $asistentesEvento2 : ${asistentesEvento1 > asistentesEvento2}")
    println("$asistentesEvento1 < $asistentesEvento2 : ${asistentesEvento1 < asistentesEvento2}")
    println("$asistentesEvento1 <= $asistentesEvento2 : ${asistentesEvento1 <= asistentesEvento2}")
    println("$asistentesEvento1 >= $asistentesEvento2 : ${asistentesEvento1 >= asistentesEvento2}")
}